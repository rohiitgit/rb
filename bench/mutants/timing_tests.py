"""Writes bench/mutants/timing_tests.txt (contract M9b, N2): every #[test] fn in crates/ whose
pass or fail reads the wall clock, as `crate name file`. A test counts when an assertion
(up to its `;`) reads the clock (`.elapsed()`, `Instant`) or bounds a duration (`<`/`>` with
`elapsed` or `Duration`), or when its name contains `stay_fast`. Tests that only print a duration
are listed as comments. bench/mutants/run.py reports a spec whose filter selects a listed test
as INVALID. Run `python3 -I bench/mutants/timing_tests.py` after adding a timing test."""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[2] / 'crates'
asserting, printing = set(), set()


def asserts_clock(body):
    """An `assert` whose statement (up to the next `;`) names the clock: linear, no regex."""
    k = body.find('assert')
    while k >= 0:
        end = body.find(';', k)
        stmt = body[k:end if end >= 0 else len(body)]
        # A clock read, or a bound on a duration; not a stored `elapsed_ms` or a configured
        # `Duration` compared for equality.
        compared = re.search(r'[<>]', stmt.replace('->', '').replace('=>', ''))
        if '.elapsed()' in stmt or 'Instant' in stmt or (
            compared and ('elapsed' in stmt or 'Duration' in stmt)
        ):
            return True
        k = body.find('assert', k + 6)
    return False

for f in sorted(root.glob('*/**/*.rs')):
    if '/target/' in str(f):
        continue
    text = f.read_text(errors='replace')
    lines = text.split('\n')
    # (start line, name) of each test fn; its body runs to the next `fn` at the same indent.
    starts = []
    pending = False
    for i, l in enumerate(lines):
        s = l.strip()
        if s.startswith('#[test]') or s.startswith('#[tokio::test'):
            pending = True
            continue
        m = re.match(r'(\s*)(?:pub(?:\(crate\))? )?(?:async )?fn (\w+)', l)
        if m:
            if pending:
                starts.append((i, m.group(2), len(m.group(1))))
            pending = False
        elif not s.startswith('#['):
            pending = False
    for i, name, indent in starts:
        j = i + 1
        while j < len(lines) and not (lines[j].startswith(' ' * indent + '}') and len(lines[j]) - len(lines[j].lstrip()) == indent):
            j += 1
        body = '\n'.join(lines[i:j + 1])
        crate = f.parts[len(root.parts)]
        where = str(f.relative_to(root))
        if 'stay_fast' in name or asserts_clock(body):
            asserting.add((crate, name, where))
        elif re.search(r'\bInstant\b|\.elapsed\(\)', body):
            printing.add((crate, name, where))
out = [
    "# Wall-clock tests: a mutant spec whose `test` filter selects one is INVALID (contract M9b N2).",
    "# Generated by bench/mutants/timing_tests.py; `crate name file`.",
]
out += [f"{c} {n} {w}" for c, n, w in sorted(asserting)]
out += ["# Print a duration only (not wall-clock):"]
out += [f"# {c} {n} {w}" for c, n, w in sorted(printing)]
target = root.parent / "bench" / "mutants" / "timing_tests.txt"
target.write_text("\n".join(out) + "\n")
print(f"wall-clock tests {len(asserting)}, print-only {len(printing)} -> {target}")
