"""Writes bench/mutants/timing_tests.txt (contract M9b, N2): every #[test] fn in crates/ whose
pass or fail reads the wall clock, as `crate path file`. A test counts when an assertion (up to
its `;`) reads the clock (`.elapsed()`, `Instant`) or bounds a duration (`<`/`>` with `elapsed`
or `Duration`), or when its name contains `stay_fast`. Tests that only print a duration are
listed as comments. bench/mutants/run.py reports a spec whose filter selects a listed test as
INVALID. Run `python3 -I bench/mutants/timing_tests.py` after adding a timing test.

`path` is the test's full path as cargo lists it (`resolve::tests::name`), because cargo runs
every test whose full path contains the filter (M9b pass 1, E4). It is read from `cargo test
-p <crate> <target> -- --list` (`--lib`, or `--test <name>` for `tests/<name>.rs`), so this
script compiles the test targets it lists; a name that is not exactly one listed path under the
file's module is an error."""
import pathlib, re, subprocess
root = pathlib.Path(__file__).resolve().parents[2] / 'crates'
asserting, printing = set(), set()


def asserts_clock(body):
    """An `assert` whose statement (up to the next `;`) names the clock: linear, no regex."""
    k = body.find('assert')
    while k >= 0:
        end = body.find(';', k)
        stmt = body[k:end if end >= 0 else len(body)]
        # A clock read, or a bound on a duration; not a stored `elapsed_ms` or a configured
        # `Duration` compared for equality.
        compared = re.search(r'[<>]', stmt.replace('->', '').replace('=>', ''))
        if '.elapsed()' in stmt or 'Instant' in stmt or (
            compared and ('elapsed' in stmt or 'Duration' in stmt)
        ):
            return True
        k = body.find('assert', k + 6)
    return False


def target_of(f):
    """The cargo test target holding a file's tests, and the module path of its items:
    `tests/e2e.rs` is `--test e2e` at the root; `src/lib.rs` is `--lib` at the root, `src/a/mod.rs`
    is `a`, `src/a/b.rs` is `a::b`."""
    parts = f.relative_to(root).parts
    if parts[1] == 'tests':
        return ('--test', f.stem), []
    rel = parts[2:]
    if rel == ('lib.rs',):
        return ('--lib',), []
    return ('--lib',), list(rel[:-1]) + ([] if rel[-1] == 'mod.rs' else [rel[-1][:-3]])


listed = {}


def full_path(crate, f, name):
    """The one path cargo lists for test `name` of file `f`."""
    target, module = target_of(f)
    if (crate, target) not in listed:
        run = subprocess.run(
            ['cargo', 'test', '-q', '-p', crate, *target, '--', '--list'],
            cwd=root.parent, capture_output=True, text=True, check=True,
        )
        listed[(crate, target)] = [
            l[: -len(': test')] for l in run.stdout.splitlines() if l.endswith(': test')
        ]
    prefix = ''.join(m + '::' for m in module)
    found = [
        p for p in listed[(crate, target)]
        if p.startswith(prefix) and p.rsplit('::', 1)[-1] == name
    ]
    if len(found) != 1:
        raise SystemExit(f'{crate} {f}: {name} is listed as {found}, not one path')
    return found[0]


for f in sorted(root.glob('*/**/*.rs')):
    if '/target/' in str(f):
        continue
    text = f.read_text(errors='replace')
    lines = text.split('\n')
    # (start line, name) of each test fn; its body runs to the next `fn` at the same indent.
    starts = []
    pending = False
    for i, l in enumerate(lines):
        s = l.strip()
        if s.startswith('#[test]') or s.startswith('#[tokio::test'):
            pending = True
            continue
        m = re.match(r'(\s*)(?:pub(?:\(crate\))? )?(?:async )?fn (\w+)', l)
        if m:
            if pending:
                starts.append((i, m.group(2), len(m.group(1))))
            pending = False
        elif not s.startswith('#['):
            pending = False
    for i, name, indent in starts:
        j = i + 1
        while j < len(lines) and not (lines[j].startswith(' ' * indent + '}') and len(lines[j]) - len(lines[j].lstrip()) == indent):
            j += 1
        body = '\n'.join(lines[i:j + 1])
        crate = f.parts[len(root.parts)]
        where = str(f.relative_to(root))
        if 'stay_fast' in name or asserts_clock(body):
            asserting.add((crate, full_path(crate, f, name), where))
        elif re.search(r'\bInstant\b|\.elapsed\(\)', body):
            printing.add((crate, full_path(crate, f, name), where))
out = [
    "# Wall-clock tests: a mutant spec whose `test` filter selects one is INVALID (contract M9b N2).",
    "# Generated by bench/mutants/timing_tests.py; `crate path file`, path as cargo lists it.",
]
out += [f"{c} {n} {w}" for c, n, w in sorted(asserting)]
out += ["# Print a duration only (not wall-clock):"]
out += [f"# {c} {n} {w}" for c, n, w in sorted(printing)]
target = root.parent / "bench" / "mutants" / "timing_tests.txt"
target.write_text("\n".join(out) + "\n")
print(f"wall-clock tests {len(asserting)}, print-only {len(printing)} -> {target}")
